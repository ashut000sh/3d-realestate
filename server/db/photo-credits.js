// Writes docs/PHOTO-CREDITS.md from the PHOTO_CREDITS list in seed-photos.js.
// Usage: npm run photo-credits
import fs from "node:fs";
import path from "node:path";
import { PHOTO_CREDITS } from "./seed-photos.js";

const out = path.resolve(import.meta.dirname, "../../docs/PHOTO-CREDITS.md");

const byListing = new Map();
for (const credit of PHOTO_CREDITS) {
  if (!byListing.has(credit.listing)) byListing.set(credit.listing, []);
  byListing.get(credit.listing).push(credit);
}

const photographers = new Set(PHOTO_CREDITS.map((c) => c.photographer));
const lines = [
  "# Photo credits",
  "",
  "<!-- Generated by `npm run photo-credits` from server/db/seed-photos.js. Don't edit by hand. -->",
  "",
  `The ${PHOTO_CREDITS.length} sample listing photos used by the seed data (\`npm run db:seed\`) are from`,
  "[Pexels](https://www.pexels.com) and are used under the",
  "[Pexels License](https://www.pexels.com/license/): free to use, including commercially,",
  "with no attribution required. We credit every photographer anyway.",
  "",
  `The files are stored in \`server/db/seed-assets/listings/\`. Photo 1 of each listing is its cover.`,
  `${photographers.size} photographers in total.`,
  "",
];
for (const [listing, credits] of byListing) {
  lines.push(
    `## ${listing}`,
    "",
    "| Photo | Photographer | Source | Licence |",
    "|---|---|---|---|",
  );
  for (const c of credits) {
    const file = c.file.split("/").pop();
    lines.push(`| \`${file}\` | ${c.photographer} | [${c.site}](${c.page}) | ${c.licence} |`);
  }
  lines.push("");
}
fs.writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), out)} (${PHOTO_CREDITS.length} photos)`);
